import { code } from '../../code.ts';
import { displayName, pascal } from '../names.ts';
import type { Plugin } from '../values.ts';

// The path of the file in plugins/ios.
export const path = ({ id }: Plugin) => `${id}/BUILD.bazel`;

// A target is only compatible when the condition holds.
const only = (condition: string) => `select({
        "${condition}": [],
        "//conditions:default": ["@platforms//:incompatible"],
    })`;

export default ({ id, backends }: Plugin) => {
  const product = pascal(id);
  // The wrapper needs the plugin's Metal shaders when it has no OpenGL ones.
  const conditions = ['//:plugins_enabled', ...(backends.includes('opengl') ? [] : ['//:metal_renderer'])];
  return code`
# Generated by plugins/tools/generate.ts from plugins/plugins/${id}/plugin.json; do not edit.
load("@rules_cc//cc:defs.bzl", "objc_library")
load("//bazel:flags.bzl", "CPP_FLAGS")

# Registers the ${displayName(id)} plugin. It links the plugin's own library, which the SDK may link as well, so the
# plugin's code exists once in an app.
objc_library(
    name = "${id}",
    srcs = ["src/${product}.mm"],
    hdrs = ["include/${product}/${product}.h"],
    copts = CPP_FLAGS,
    includes = ["include"],
    module_name = "${product}",
    target_compatible_with = ${conditions.map(only).join(' + ')},
    visibility = ["//visibility:public"],
    deps = ["//plugins/plugins/${id}"],
)
`;
};
