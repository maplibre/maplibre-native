import { code } from '../../code.ts';
import { androidClass, androidNamespace, header, registerFunction } from '../names.ts';
import type { AndroidValues } from '../values.ts';

// The path of the file in plugins/android.
export const path = ({ plugin: { id } }: AndroidValues) => `${id}/src/main/cpp/plugin.cpp`;

// The name of a JNI function: the underscores of the class name are escaped as _1 and the dots become underscores.
const jniName = (qualifiedName: string) => qualifiedName.replaceAll('_', '_1').replaceAll('.', '_');

export default ({ plugin: { id } }: AndroidValues) => code`
// clang-format off
// Generated by plugins/tools/generate.ts from plugins/plugins/${id}/plugin.json; do not edit.
#include <jni.h>
#include <dlfcn.h>
#include <mln/plugin/plugin_api.h>
#include "${header(id)}"

namespace {
void throwRegistrationError(JNIEnv* env, const char* message) {
    env->ThrowNew(env->FindClass("java/lang/IllegalStateException"), message);
}
} // namespace

extern "C" JNIEXPORT void JNICALL Java_${jniName(`${androidNamespace(id)}.${androidClass(id)}`)}_registerNative(JNIEnv* env, jclass, jstring libraryName) {
    const char* name = env->GetStringUTFChars(libraryName, nullptr);
    if (!name) return;
    // Resolve from the renderer MapLibre already loaded, without loading a second registry.
    void* host = dlopen(name, RTLD_NOW | RTLD_NOLOAD);
    env->ReleaseStringUTFChars(libraryName, name);
    if (!host) {
        throwRegistrationError(env, "Initialize MapLibre with the selected renderer before registering plugins");
        return;
    }

    auto registerPlugin = reinterpret_cast<mln_plugin_register_function_v1>(dlsym(host, "mln_plugin_register_v1"));
    if (!registerPlugin) {
        dlclose(host);
        throwRegistrationError(env, "This MapLibre Android build does not export the plugin API");
        return;
    }

    char error[512] = {};
    const auto status = ${registerFunction(id)}(registerPlugin, error, sizeof(error));
    dlclose(host); // MapLibre keeps its original library reference for the process lifetime.
    if (status != MLN_PLUGIN_STATUS_OK && status != MLN_PLUGIN_STATUS_ALREADY_REGISTERED) {
        throwRegistrationError(env, error);
    }
}
`;
