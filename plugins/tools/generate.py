#!/usr/bin/env python3
"""Generates the platform wrappers of the plugins in plugins/plugins/ from their plugin.json.

Usage: python3 plugins/tools/generate.py [--check] [--platform android|ios]   (default: every platform)

* plugins/android/<id>/: a Gradle library module with the plugin's native code, its JNI registration function, a
  Kotlin `<Name>Plugin.register()` and the demo metadata (`assets/demo/<id>/`) the demo app lists.
* plugins/ios/<id>/: a Bazel library with an Objective-C `MLN<Name>Plugin` class that registers the plugin, and the
  demo metadata (`demo/`) the demo app lists. plugins/ios/ also has a registry that registers any plugin by its ID.

The outputs are committed. `--check` writes nothing and fails when they differ from plugin.json, which is how CI
catches an edited plugin.json or template whose output was not regenerated.
"""

import argparse
import json
import os
import shutil
import sys
from pathlib import Path, PurePosixPath

sys.dont_write_bytecode = True  # no __pycache__ next to the tools
sys.path.insert(0, str(Path(__file__).resolve().parent))
import config  # noqa: E402

TEMPLATES = config.TOOLS_ROOT / "templates"
ANDROID_ROOT = config.PLUGINS_ROOT / "android"
IOS_ROOT = config.PLUGINS_ROOT / "ios"
# Build outputs that live next to generated files and are ignored by git.
IGNORED_DIRECTORIES = {"build", ".cxx", ".gradle"}
GENERATED_NOTE = "Generated by plugins/tools/generate.py from plugins/plugins/{id}/plugin.json; do not edit."


def _fill(template, values):
    text = (TEMPLATES / template).read_text(encoding="utf-8")
    for key, value in values.items():
        text = text.replace("@@" + key + "@@", value)
    if "@@" in text:
        raise config.ConfigError(f"Unfilled placeholder in {template}")
    return text


def _jni_mangle(name):
    return name.replace("_", "_1").replace(".", "_")


def _kotlin_bool(value):
    return "true" if value else "false"


def _header_include(plugin):
    """The plugin header as an include path relative to one of the include directories."""
    header = PurePosixPath(plugin["header"])
    return next(str(header.relative_to(PurePosixPath(d))) for d in map(PurePosixPath, plugin["includeDirectories"])
                if (d == header.parent or d in header.parents) and d != PurePosixPath("."))


def _demo_metadata(plugin, style, **extra):
    """The demo.json the demo apps list: what to show for a plugin that has a demo style."""
    metadata = {
        "id": plugin["id"],
        "displayName": plugin["displayName"],
        "description": plugin["description"],
        **extra,
        "style": style,
    }
    if "camera" in plugin["demo"]:
        metadata["camera"] = plugin["demo"]["camera"]
    return json.dumps(metadata, indent=2) + "\n"


def android_outputs(plugin, versions):
    """The files of plugins/android/<id>/, keyed by their path inside it."""
    android = plugin["android"]
    module_directory = ANDROID_ROOT / plugin["id"] / "src/main/cpp"
    plugin_root = os.path.relpath(plugin["directory"], module_directory)
    include_directories = plugin["includeDirectories"]
    header_include = _header_include(plugin)
    namespace_path = android["namespace"].replace(".", "/")
    backends = plugin["backends"]
    values = {
        "ID": plugin["id"],
        "PRODUCT": android["className"].removesuffix("Plugin"),
        "DISPLAY_NAME": plugin["displayName"],
        "VERSION": plugin["version"],
        "NAMESPACE": android["namespace"],
        "CLASS_NAME": android["className"],
        "QUALIFIED_CLASS_NAME": android["qualifiedClassName"],
        "LIBRARY_NAME": android["libraryName"],
        "COMPILE_SDK": str(versions["compileSdk"]),
        "MIN_SDK": str(versions["minSdk"]),
        "NDK_VERSION": versions["ndkVersion"],
        "PLUGIN_ROOT": plugin_root,
        "SOURCES": "".join(f'    "${{PLUGIN_ROOT}}/{s}"\n' for s in plugin["sources"]),
        "INCLUDE_DIRECTORIES": "".join(f'    "${{PLUGIN_ROOT}}/{d}"\n' for d in include_directories),
        "HEADER_INCLUDE": header_include,
        "REGISTER_FUNCTION": plugin["registerFunction"],
        "JNI_CLASS": _jni_mangle(android["qualifiedClassName"]),
        "BACKENDS": ", ".join(backends),
        "OPENGL": _kotlin_bool("opengl" in backends),
        "VULKAN": _kotlin_bool("vulkan" in backends),
    }
    outputs = {
        "build.gradle.kts": _fill("android/build.gradle.kts.in", values),
        "consumer-rules.pro": _fill("android/consumer-rules.pro.in", values),
        "src/main/cpp/CMakeLists.txt": _fill("android/CMakeLists.txt.in", values),
        "src/main/cpp/plugin.cpp": _fill("android/plugin.cpp.in", values),
        f"src/main/java/{namespace_path}/{android['className']}.kt": _fill("android/Plugin.kt.in", values),
    }
    demo = plugin["demo"]
    if "style" in demo:
        style = demo["style"]
        if not style.startswith("https://"):
            outputs[f"src/main/assets/demo/{plugin['id']}/style.json"] = (plugin["directory"] / style).read_text(encoding="utf-8")
            style = f"asset://demo/{plugin['id']}/style.json"
        outputs[f"src/main/assets/demo/{plugin['id']}/demo.json"] = _demo_metadata(
            plugin, style, registerClass=android["qualifiedClassName"])
    return outputs


def android_files(plugins):
    versions = config.android_versions()
    files = {
        "README.md": "Android wrapper modules, generated by `python3 plugins/tools/generate.py` from the\n"
                     "`plugin.json` of each plugin in `plugins/plugins/`. Do not edit them; change the plugin or\n"
                     "`plugins/tools/templates/android/` and regenerate.\n",
        ".gitignore": "/*/build/\n/*/.cxx/\n/*/.gradle/\n",
    }
    for plugin in plugins:
        if plugin["android"]["supported"]:
            for path, content in android_outputs(plugin, versions).items():
                files[f"{plugin['id']}/{path}"] = content
    return files


PLUGINS_ENABLED = """    target_compatible_with = select({
        "//:plugins_enabled": [],
        "//conditions:default": ["@platforms//:incompatible"],
    }),"""
PLUGINS_ENABLED_METAL = """    target_compatible_with = select({
        "//:plugins_enabled": [],
        "//conditions:default": ["@platforms//:incompatible"],
    }) + select({
        "//:metal_renderer": [],
        "//conditions:default": ["@platforms//:incompatible"],
    }),"""


def _objc_string(value):
    return value.replace("\\", "\\\\").replace('"', '\\"')


def ios_outputs(plugin):
    """The files of plugins/ios/<id>/, keyed by their path inside it."""
    apple = plugin["apple"]
    product = apple["product"]
    plugin_id = plugin["id"]
    outputs = {}
    demo_targets = ""
    demo = plugin["demo"]
    if "style" in demo:
        # An app bundle is flat, so the files are named after the plugin to keep them apart.
        sources = [f"demo/{plugin_id}.demo.json"]
        style = demo["style"]
        if not style.startswith("https://"):
            outputs[f"demo/{plugin_id}.style.json"] = (plugin["directory"] / style).read_text(encoding="utf-8")
            sources.append(f"demo/{plugin_id}.style.json")
            style = f"{plugin_id}.style.json"
        outputs[f"demo/{plugin_id}.demo.json"] = _demo_metadata(plugin, style)
        demo_targets = '\nfilegroup(\n    name = "demo",\n    srcs = [\n' + "".join(
            f'        "{source}",\n' for source in sources) + '    ],\n    visibility = ["//visibility:public"],\n)\n'
    values = {
        "ID": plugin_id,
        "PRODUCT": product,
        "CLASS": apple["className"],
        "SWIFT_NAME": apple["swiftName"],
        "ERROR_DOMAIN": _objc_string(apple["errorDomain"]),
        "DISPLAY_NAME": _objc_string(plugin["displayName"]),
        "VERSION": _objc_string(plugin["version"]),
        "REGISTER_FUNCTION": plugin["registerFunction"],
        "HEADER_INCLUDE": _header_include(plugin),
        "COMPATIBLE": PLUGINS_ENABLED_METAL if apple["metalOnly"] else PLUGINS_ENABLED,
        "DEMO": demo_targets,
    }
    outputs["BUILD.bazel"] = _fill("ios/BUILD.bazel.in", values).rstrip("\n") + "\n"
    outputs[f"include/{product}/{product}.h"] = _fill("ios/Plugin.h.in", values)
    outputs[f"src/{product}.mm"] = _fill("ios/Plugin.mm.in", values)
    return outputs


def ios_files(plugins):
    supported = [plugin for plugin in plugins if plugin["apple"]["supported"]]
    files = {
        "README.md": "iOS wrapper libraries, generated by `python3 plugins/tools/generate.py` from the `plugin.json`\n"
                     "of each plugin in `plugins/plugins/`. Do not edit them; change the plugin or\n"
                     "`plugins/tools/templates/ios/` and regenerate.\n",
    }
    for plugin in supported:
        for path, content in ios_outputs(plugin).items():
            files[f"{plugin['id']}/{path}"] = content
    products = [(plugin["id"], plugin["apple"]) for plugin in supported]
    demo_ids = [plugin["id"] for plugin in supported if "style" in plugin["demo"]]
    values = {
        "IMPORTS": "\n".join(f"#import <{apple['product']}/{apple['product']}.h>" for _, apple in products),
        "IDENTIFIERS": "\n".join(f'        @"{plugin_id}",' for plugin_id, _ in products),
        "CASES": "\n".join(
            f'    if ([identifier isEqualToString:@"{plugin_id}"]) {{\n'
            f'        return [{apple["className"]} registerPluginWithError:error];\n'
            f'    }}' for plugin_id, apple in products),
        "DEPS": "\n".join(f'        "//plugins/ios/{plugin_id}",' for plugin_id, _ in products),
        "DEMOS": "\n".join(f'        "//plugins/ios/{plugin_id}:demo",' for plugin_id in demo_ids),
    }
    files["BUILD.bazel"] = _fill("ios/RegistryBUILD.bazel.in", values)
    files["include/PluginRegistry/PluginRegistry.h"] = _fill("ios/Registry.h.in", values)
    files["src/PluginRegistry.mm"] = _fill("ios/Registry.mm.in", values)
    return files


def sync(directory, files, check):
    """Make `directory` contain exactly `files`. Returns the paths that were (or would be) changed."""
    changed = []
    for path, content in sorted(files.items()):
        target = directory / path
        if not target.is_file() or target.read_text(encoding="utf-8") != content:
            changed.append(f"{path}")
            if not check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content, encoding="utf-8")
    leftovers = []
    if directory.is_dir():
        for root, directories, names in os.walk(directory):
            directories[:] = [d for d in directories if d not in IGNORED_DIRECTORIES]
            for name in names:
                relative = (Path(root) / name).relative_to(directory).as_posix()
                if relative not in files:
                    leftovers.append(relative)
    for relative in sorted(leftovers):
        changed.append(f"{relative} (not generated)")
        if not check:
            (directory / relative).unlink()
    if not check and directory.is_dir():
        # Remove directories emptied by a renamed or removed plugin.
        for root, directories, _ in os.walk(directory, topdown=False):
            for name in directories:
                path = Path(root) / name
                if name not in IGNORED_DIRECTORIES and path.is_dir() and not any(path.iterdir()):
                    shutil.rmtree(path)
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the generated files are out of date")
    parser.add_argument("--platform", choices=["android", "ios"], help="only this platform (default: all)")
    arguments = parser.parse_args()
    try:
        plugins = config.discover()
        changed = {}
        if arguments.platform in (None, "android"):
            changed["plugins/android"] = sync(ANDROID_ROOT, android_files(plugins), arguments.check)
        if arguments.platform in (None, "ios"):
            changed["plugins/ios"] = sync(IOS_ROOT, ios_files(plugins), arguments.check)
    except config.ConfigError as error:
        sys.exit(f"error: {error}")
    stale = [f"  {directory}/{path}" for directory, paths in changed.items() for path in paths]
    if arguments.check:
        if stale:
            sys.exit("Generated plugin wrappers are out of date. Run python3 plugins/tools/generate.py and commit "
                     "the result:\n" + "\n".join(stale))
        print("Generated plugin wrappers are up to date.")
    else:
        print(f"Generated plugin wrappers for {len(plugins)} plugins ({len(stale)} files changed).")
        for line in stale:
            print(line)


if __name__ == "__main__":
    main()
